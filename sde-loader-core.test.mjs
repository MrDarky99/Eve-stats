import {normalizeTables,findTable,tableJsonlUrl,parseJsonl,typeName} from './sde-loader-core.mjs';
let n=0;const ok=(v,msg)=>{if(!v)throw new Error(msg);n++};
const arr=[{name:'blueprints',jsonl:{url:'b'}},{name:'types',jsonl:{url:'t'}}];
ok(findTable(arr,'blueprints')===arr[0],'array index');
const obj={blueprints:{jsonl:{url:'b'}},types:{jsonl:{url:'t'}}};
ok(findTable(obj,'types').name==='types','object index');
ok(normalizeTables(null).length===0,'null normalization');
ok(tableJsonlUrl(findTable(obj,'blueprints'))==='b','url extraction');
ok(parseJsonl('{"x":1}\n{"x":2}').length===2,'jsonl parsing');
ok(typeName({name:{en:'Astero'}})==='Astero','localized names');
ok(typeName({typeName:'Rifter'})==='Rifter','fallback name');
console.log(`SDE loader core: PASS (${n} assertions)`);
